    // =========================================================================
    // PASO 2: [INTENTA ESCRIBIR TU TABLA PADRE AQUI (ESTILO DJANGO)]
    // Qué hace: Define una tabla principal para probar tipos, checks, unique y defaults.
    // Cómo lo hace: Hereda de Models::Model y usa los constructores de DjangoFields.hpp.
    // =========================================================================
    class MiTablaPadreDePrueba final : public Model {
    public:
        // ---> AQUI DALE NOMBRE A TU TABLA, INDICES Y UNIQUE COMPUESTOS <---
        MetaOptions meta() const override {
            MetaOptions m;
            m.db_table = "LaboratorioDispositivos"; // Intenta cambiarlo por "SELECT" o "TABLE" para ver el error 42601

            // ---> AQUI DALE UN INDEX <---
            m.indexes = {
                Index("idx_lab_codigo_serie", {"codigo_serie"}, true),
                Index("idx_lab_estado",       {"estado"})
            };

            // ---> AQUI DALE UN UNIQUE CONSTRAINT COMPUESTO <---
            m.unique_constraints = {
                UniqueConstraint("uq_ubicacion_rack", {"ubicacion", "numero_rack"})
            };
            return m;
        }

        // ---> AQUI INTENTA ESCRIBIR TUS COLUMNAS, TIPOS, DEFAULTS Y CHECKS <---
        std::vector<Field> fields() const override {
            return {
                // 1. Clave primaria autoincremental (INTEGER GENERATED BY DEFAULT AS IDENTITY)
                AutoField("id_dispositivo"),

                // 2. VARCHAR(n) con UNIQUE
                CharField("codigo_serie", 32).unique(),

                // 3. VARCHAR(n) con valor DEFAULT validado contra la longitud máxima
                CharField("ubicacion", 48).default_val("Sala Servidores Ushuaia"),

                // 4. ---> AQUI PROBA UN CHECK <---
                // Entero pequeño con restricción CHECK tanto en SQL como con lambda evaluadora para el DEFAULT
                SmallIntegerField("numero_rack")
                    .default_val(1)
                    .check("numero_rack >= 1 AND numero_rack <= 40",
                           [](const String& val) {
                               int n = val.toInt();
                               return n >= 1 && n <= 40;
                           }),

                // 5. ---> AQUI PROBA UN NUMERIC(p, s) <---
                // Prueba cambiar el default_val("99999.99") para disparar numeric field overflow (SQLSTATE 22003)
                DecimalField("voltaje_alimentacion", 5, 2).default_val("12.50"),

                // 6. ---> AQUI PROBA TU ENUM <---
                // Prueba poner default_val("VALOR_INEXISTENTE") para ver el error 22P02 de PostgreSQL
                EnumField("estado", "mi_estado_dispositivo_enum").default_val("ACTIVO"),

                // 7. ---> AQUI PROBA UN JSON <---
                // Prueba poner default_val("texto_no_json") para ver el error 22P02
                JSONField("metadatos_json").default_val("{\"firmware\":1}"),

                // 8. Booleano nativo PostgreSQL
                BooleanField("habilitado").default_val("TRUE")
            };
        }
    };

    // =========================================================================
    // PASO 3: [INTENTA ESCRIBIR UNA TABLA HIJA CON FOREIGN KEY AQUI]
    // Qué hace: Define una tabla relacionada para probar integridad referencial.
    // Cómo lo hace: Usa ForeignKey(...) apuntando a la PK o columna UNIQUE de la tabla padre.
    // =========================================================================
    class MiTablaHijaDePrueba final : public Model {
    public:
        MetaOptions meta() const override {
            return { "TelemetriaLaboratorio" };
        }

        std::vector<Field> fields() const override {
            return {
                AutoField("id_telemetria"),

                // ---> AQUI PROBA UNA FOREIGN KEY <---
                // Apunta a LaboratorioDispositivos.id_dispositivo.
                // Prueba cambiar "id_dispositivo" por "ubicacion" (que no es UNIQUE) para ver el error 42830!
                ForeignKey("id_dispositivo", "LaboratorioDispositivos", "id_dispositivo", CASCADE),

                FloatField("temperatura_medida").default_val(22.4f),
                BigIntegerField("timestamp_unix").default_val(0)
            };
        }
    };

    // =========================================================================
    // PASO 4: [INTENTA PROBAR OPERACIONES DIRECTAS DEL MOTOR DDL AQUI]
    // Qué hace: Ejecuta el sandbox manual mostrando cada respuesta en formato terminal psql.
    // Cómo lo hace: Activa setSerialOutput(true) en DdlDiagnosticConsole y corre tus modelos y ALTERs.
    // =========================================================================
    inline void ejecutarSandboxManual() {
        DdlDiagnosticConsole& console = DdlDiagnosticConsole::getInstance();
        console.setSerialOutput(true); // Imprime cada comando y error exactamente como la terminal psql

        probarMisEnumsManuales();

        bannerManual("2. MIGRANDO TU TABLA PADRE E HIJA (ESTILO DJANGO)");
        MiTablaPadreDePrueba tablaPadre;
        tablaPadre.migrate(false);

        MiTablaHijaDePrueba tablaHija;
        tablaHija.migrate(false);

        bannerManual("3. [AQUI PROBA TUS ALTER TABLE / DROP TABLE / CREATE TABLE FLUIDO]");
        ModuloDDL& ddl = ModuloDDL::getInstance();

        // ---> AQUI PROBA UN ALTER TABLE RENAME COLUMN <---
        ddl.alterTableRenameColumn("LaboratorioDispositivos", "habilitado", "activo_en_bus");

        // ---> AQUI PROBA CAMBIAR UN DEFAULT CON ALTER TABLE <---
        ddl.alterTableAlterColumnDefault("LaboratorioDispositivos", "ubicacion", true, "DataCenter Principal");

        // ---> AQUI PROBA PROVOCAR UN ERROR A PROPOSITO PARA VER LA TERMINAL PSQL <---
        // Ejemplo: Intentar borrar la tabla padre sin CASCADE teniendo a TelemetriaLaboratorio apuntándole:
        Serial.println("\n--> Probando DROP TABLE restringido (debe mostrar ERROR 2BP01 y HINT):");
        ddl.dropTable("LaboratorioDispositivos", false, ReferentialAction::RESTRICT);

        // Ejemplo: Intentar crear una tabla en vivo con una combinación ilegal (NOT NULL + ON DELETE SET NULL):
        Serial.println("\n--> Probando combinacion determinista prohibida (NOT NULL + ON DELETE SET NULL):");
        ddl.createTable("TablaMalDisenada")
           .column("id", PgDataType::INTEGER).primaryKey()
           .column("padre_id", PgDataType::INTEGER).notNull()
               .references("LaboratorioDispositivos", "id_dispositivo", ReferentialAction::SET_NULL)
           .execute();

        // Limpieza opcional de las tablas de tu sandbox antes de pasar al resto del sistema
        Serial.println("\n--> Limpiando tablas del Sandbox Manual con CASCADE:");
        ddl.dropTable("LaboratorioDispositivos", true, ReferentialAction::CASCADE);
        ddl.dropTable("TelemetriaLaboratorio", true, ReferentialAction::CASCADE);
    }

