#pragma once
#include <Arduino.h>
#include <vector>
#include "PostgresDataTypes.hpp"

namespace DbNotRuntime::Standard {

    // Define las acciones referenciales en ON DELETE / ON UPDATE según Sección 3 de informe.md.
    enum class ReferentialAction : uint8_t {
        NO_ACTION = 0,
        RESTRICT,
        CASCADE,
        SET_NULL,
        SET_DEFAULT
    };

    // Define el tipo de coincidencia para claves foráneas (MATCH FULL / PARTIAL / SIMPLE).
    enum class MatchType : uint8_t {
        SIMPLE = 0,
        PARTIAL,
        FULL
    };

    // Define el modo de columna autogenerada según el estándar SQL/PostgreSQL (GENERATED ... AS IDENTITY).
    enum class IdentityGeneration : uint8_t {
        NONE = 0,
        ALWAYS,             // GENERATED ALWAYS AS IDENTITY
        BY_DEFAULT,         // GENERATED BY DEFAULT AS IDENTITY
        STORED_EXPRESSION   // GENERATED ALWAYS AS (expr) STORED
    };

    // Define el método de acceso físico de un índice en PostgreSQL.
    enum class IndexMethod : uint8_t {
        BTREE = 0,
        HASH,
        GIST,
        GIN,
        BRIN
    };

    // Define la dirección de ordenamiento y posición de nulos en índices.
    enum class SortDirection : uint8_t { ASC = 0, DESC = 1 };
    enum class NullsOrder : uint8_t { FIRST = 0, LAST = 1 };

    // Define la persistencia física de una tabla en PostgreSQL.
    enum class TablePersistence : uint8_t {
        PERMANENT = 0,
        TEMPORARY,
        UNLOGGED
    };

    // Usa puntero a función nativo (4 bytes en Xtensa) en lugar de std::function pesado para cuidar la pila de FreeRTOS.
    using CheckEvaluatorFn = bool (*)(const String&);

    // Estructura que representa el estado completo de una columna física en PostgreSQL con soporte move-semantics.
    struct ColumnConstraintDef {
        String columnName = "";
        PgDataType dataType = PgDataType::TEXT;
        String customTypeName = ""; // Nombre del ENUM o DOMAIN si aplica
        bool isArray = false;

        uint16_t maxLength = 0;     // Para VARCHAR(n), CHAR(n), BIT(n)
        uint8_t precision = 0;      // Para NUMERIC(p,s)
        uint8_t scale = 0;          // Para NUMERIC(p,s)
        IntervalField intervalField = IntervalField::NONE;

        bool isPrimaryKey = false;
        bool isNotNull = false;
        bool isUnique = false;

        IdentityGeneration identityMode = IdentityGeneration::NONE;
        int32_t identityStart = 1;
        int32_t identityIncrement = 1;

        bool hasDefault = false;
        String defaultValue = "";

        String collation = "default";
        String comment = "";

        bool hasCheck = false;
        String checkConstraintName = "";
        String checkExpression = "";
        CheckEvaluatorFn checkFn = nullptr;

        bool isForeignKey = false;
        String fkConstraintName = "";
        String referencedTable = "";
        String referencedColumn = "";
        ReferentialAction onDelete = ReferentialAction::NO_ACTION;
        ReferentialAction onUpdate = ReferentialAction::NO_ACTION;
        MatchType matchType = ReferentialAction::NO_ACTION == ReferentialAction::NO_ACTION ? MatchType::SIMPLE : MatchType::SIMPLE;
        bool deferrable = false;
        bool initiallyDeferred = false;

        ColumnConstraintDef() = default;
        ColumnConstraintDef(const ColumnConstraintDef&) = default;
        ColumnConstraintDef(ColumnConstraintDef&&) noexcept = default;
        ColumnConstraintDef& operator=(const ColumnConstraintDef&) = default;
        ColumnConstraintDef& operator=(ColumnConstraintDef&&) noexcept = default;
    };

    // Representa una restricción a nivel de tabla (compuesta o con nombre explícito CONSTRAINT).
    struct TableLevelConstraintDef {
        String constraintName = "";
        enum class Type : uint8_t { PRIMARY_KEY, UNIQUE, CHECK, FOREIGN_KEY } type;
        std::vector<String> localColumns;
        String referencedTable = "";
        std::vector<String> referencedColumns;
        ReferentialAction onDelete = ReferentialAction::NO_ACTION;
        ReferentialAction onUpdate = ReferentialAction::NO_ACTION;
        String checkExpression = "";
        bool deferrable = false;
        bool initiallyDeferred = false;
    };

    // Representa un objeto SEQUENCE independiente o vinculado (OWNED BY) en PostgreSQL.
    struct SequenceDefinition {
        String sequenceName = "";
        PgDataType dataType = PgDataType::BIGINT;
        int64_t startValue = 1;
        int64_t incrementBy = 1;
        int64_t minValue = 1;
        int64_t maxValue = 2147483647LL;
        bool cycle = false;
        uint16_t cache = 1;
        String ownedByTable = "";
        String ownedByColumn = "";
    };

    // Representa un índice físico de PostgreSQL (CREATE [UNIQUE] INDEX ... USING method ...).
    struct IndexDefinition {
        String indexName = "";
        String tableName = "";
        bool isUnique = false;
        IndexMethod method = IndexMethod::BTREE;
        std::vector<String> keyColumns;
        std::vector<String> includeColumns; // INCLUDE (...)
        SortDirection direction = SortDirection::ASC;
        NullsOrder nullsOrder = NullsOrder::LAST;
        String wherePredicate = "";         // Índice parcial WHERE ...
        String tablespace = "pg_default";
    };

} // namespace DbNotRuntime::Standard